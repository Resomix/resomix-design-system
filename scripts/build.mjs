// Builds the v3 "calm" outputs from tokens/v3/tokens.json and tokens/compat.json:
//   tokens/resomix.css   v3 tokens (Studio and Daylight), type styles and the aliases for today's names
//   tokens/pixels.css    the --px-N size steps the webapp layout uses
//   README.md, docs/migration-v3.md   token tables between <!-- generated:... --> markers
// Run: npm run build
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const v3 = JSON.parse(read('tokens/v3/tokens.json'));
const compat = JSON.parse(read('tokens/compat.json'));
const header = '/* Generated by scripts/build.mjs from tokens/v3/tokens.json and tokens/compat.json. Do not edit by hand. */\n';

const decl = (name, value) => `  --${name}: ${value};`;
const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}\n`;

// Colours: everything on :root (Studio), then what Daylight changes.
const colors = v3.color.tokens;
const studio = colors.map((t) => decl(t.name, t.value.dark));
const daylight = colors.filter((t) => t.value.light !== t.value.dark).map((t) => decl(t.name, t.value.light));

const families = Object.entries(compat.families).map(([k, v]) => decl(`font-${k}`, v));
const scalar = (group) => group.tokens.map((t) => decl(t.name, t.value));
const shadowsDark = v3.shadow.tokens.map((t) => decl(t.name, t.value.dark));
const shadowsLight = v3.shadow.tokens.map((t) => decl(t.name, t.value.light));

const typeClasses = v3.type.groups.flatMap((g) => g.styles.map((s) => {
  const family = s.family ?? g.family;
  return `.type-${s.name} {\n  font-family: var(--font-${family});\n  font-size: ${s.fontSize};\n  line-height: ${s.lineHeight};\n` +
    `  font-weight: ${s.fontWeight};\n` + (s.letterSpacing ? `  letter-spacing: ${s.letterSpacing};\n` : '') + '}\n';
}));

const aliases = Object.entries(compat.aliases).map(([name, a]) => decl(name, a.to));

const css = `${header}
/* v3 tokens. Studio (dark) is the default; Daylight applies under ${compat.themes.light}. */
${block(':root', [...studio, '', ...families, '', ...scalar(v3.spacing), '', ...scalar(v3.radius), '', ...shadowsDark, '', ...scalar(v3.size), '', ...scalar(v3.timing)])}
${block(compat.themes.light, [...daylight, '', ...shadowsLight])}
@media (prefers-reduced-motion: reduce) {
  :root { --duration-fast: 0ms; --duration-base: 0ms; --duration-slow: 0ms; }
}

/* Today's names, pointed at v3. Declared on every theme selector so each one resolves against its own theme. */
${block(`:root, ${compat.themes.light}`, aliases)}
/* Type styles. Sentence case; nothing below 12px. */
${typeClasses.join('\n')}`;
writeFileSync(new URL('tokens/resomix.css', root), css);

// --px-N = N/16 rem; html font-size scales with the viewport, so every step does too.
const steps = compat.px.split(/\s+/).map(Number);
const pxName = (n) => String(n).replace('.', '-');
const rem = (n) => `${+(n / 16).toFixed(6)}rem`;
const pixels = `${header}
html { font-size: ${compat.layout.rootFontSize.desktop}; }
@media (max-width: 1023px) { html { font-size: ${compat.layout.rootFontSize.mobile}; } }

${block(':root', steps.map((n) => decl(`px-${pxName(n)}`, rem(n))))}`;
writeFileSync(new URL('tokens/pixels.css', root), pixels);

// Markdown tables.
const code = (s) => `\`${String(s).replace(/\|/g, '\\|')}\``;
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`,
  ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const groupOf = (name) => (name.startsWith('brand-') ? 'Brand' : name.startsWith('bg-') ? 'Grounds'
  : name.startsWith('text-') ? 'Text' : name.startsWith('border-') ? 'Edges'
  : name.startsWith('status-') ? 'Status' : name.startsWith('data-') || name === 'tool-ink' ? 'Data and tools' : 'Accent and focus');
const colorOrder = ['Grounds', 'Text', 'Edges', 'Accent and focus', 'Status', 'Data and tools', 'Brand'];
const colorTables = colorOrder.map((g) => `**${g}**\n\n` + table(['Token', 'Studio', 'Daylight', 'Use'],
  colors.filter((t) => groupOf(t.name) === g).map((t) => [code(`--${t.name}`), code(t.value.dark), code(t.value.light), cell(t.usage)]))).join('\n\n');
const typeTable = table(['Class', 'Family', 'Size / line', 'Weight', 'Use'],
  v3.type.groups.flatMap((g) => g.styles.map((s) => [code(`.type-${s.name}`), s.family ?? g.family,
    `${s.fontSize} / ${s.lineHeight}`, s.fontWeight, cell(s.usage)])));
const scalarTable = (group) => table(['Token', 'Value', 'Use'], group.tokens.map((t) => [code(`--${t.name}`), code(t.value), cell(t.usage)]));
const shadowTable = table(['Token', 'Studio', 'Daylight', 'Use'],
  v3.shadow.tokens.map((t) => [code(`--${t.name}`), code(t.value.dark), code(t.value.light), cell(t.usage)]));

const tokensMd = `### Colour

${colorTables}

### Type

${table(['Family', 'Stack'], Object.entries(compat.families).map(([k, v]) => [code(`--font-${k}`), code(v)]))}

${typeTable}

### Spacing

${scalarTable(v3.spacing)}

### Radius

${scalarTable(v3.radius)}

### Depth

${shadowTable}

### Sizes

${scalarTable(v3.size)}

### Motion

${scalarTable(v3.timing)}`;

const mapMd = table(['Name the app uses today', 'Now resolves to', 'Note'],
  Object.entries(compat.aliases).map(([n, a]) => [code(`--${n}`), code(a.to), cell(a.note)]));

const fill = (path, marker, body) => {
  const text = read(path);
  const re = new RegExp(`(<!-- generated:${marker} -->)[\\s\\S]*?(<!-- /generated:${marker} -->)`);
  if (!re.test(text)) throw new Error(`${path}: missing <!-- generated:${marker} --> markers`);
  writeFileSync(new URL(path, root), text.replace(re, `$1\n${body}\n$2`));
};
fill('README.md', 'tokens', tokensMd);
fill('docs/migration-v3.md', 'map', mapMd);

console.log(`resomix.css: ${colors.length} colours, ${typeClasses.length} type styles, ${aliases.length} aliases · pixels.css: ${steps.length} steps`);
